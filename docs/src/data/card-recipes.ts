import type { AtlasCardModel, CardFact, CardIntent, CardPurpose } from './card-model';

export interface CardRecipe {
  id: string;
  label: string;
  category: string;
  description: string;
  model: AtlasCardModel;
}

const fact = (
  key: string,
  label: string,
  value: CardFact['value'],
  format?: CardFact['format'],
  currency?: string,
): CardFact => ({
  key,
  label,
  value,
  ...(format ? { format } : {}),
  ...(currency ? { currency } : {}),
});
function recipe(
  id: string,
  label: string,
  category: string,
  description: string,
  kind: CardPurpose,
  model: Omit<AtlasCardModel, 'id' | 'kind' | 'source'>,
): CardRecipe {
  return {
    id,
    label,
    category,
    description,
    model: {
      id: `sample-${id}`,
      kind,
      ...model,
      source: {
        label: 'Local sample dataset',
        sourceId: `fixture:${id}`,
        observedAt: '2026-10-14T06:00:00Z',
        mode: 'recorded',
      },
    },
  };
}
const action = (id: string, label: string, intent: CardIntent = 'inspect') => ({
  id: `card-${id}`,
  label,
  intent,
});

