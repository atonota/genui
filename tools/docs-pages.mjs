import { accessSync, constants, existsSync, statSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import ts from 'typescript';

// GitHub Pages adapter, loaded only for GENUX_DOCS_PAGES=1 builds. Astro's base prefixes its own
// /_astro/ output; authored root-absolute site URLs are prefixed here exactly once, after the
// presentation gate has validated the canonical root paths. Local builds keep the root base.
export const PAGES_SITE = 'https://atonota.github.io';
export const PAGES_BASE = '/genux';
const BASE = `${PAGES_BASE}/`;
const ASSETS = `${BASE}_astro/`;
const URL_KEYS = new Set(['href', 'src', 'url', 'to', 'path', 'pathname', 'route', 'action']);
const URL_ATTRIBUTES = [
  'href',
  'src',
  'action',
  'poster',
  'component-url',
  'renderer-url',
  'before-hydration-url',
];
const SCRIPT_TYPES = new Set(['', 'module', 'text/javascript', 'application/javascript']);
// Declared public fixtures that are deliberately never emitted (AvatarDemo's missing image shows
// the initials fallback). They get the base wherever they appear, so production never requests
// the site root; validateArtifact() still requires every other linked file to exist.
const FIXTURES = new Set(['/genux-avatar-missing-example.png']);
const PRIVATE = /(^|\/)(\.env[^/]*|evidence|backups?|[^/]+\.(bak|orig|swp)|raw[^/]*\.html)(\/|$)/i;
const cssUrl = /url\(\s*(['"]?)([^'")]+)\1\s*\)/g;
const srcsetUrl = /(^|,\s*)([^\s,]+)/g;
const refresh = /^(\s*\d+\s*[;,]\s*url\s*=\s*['"]?)([^'"\s]+)/i;

// Published URL for a root-absolute site URL, or null to leave it unchanged. Only first segments
// generated by this build count, so /tokens/ becomes /genux/tokens/. The hosting base /genux
// (bare or with a trailing slash, query or hash) is already based and stays unchanged, so the
// product route /genux/ is authored BASE-aware (genuxPageHref) as /genux/genux/ before this
// adapter; `/` and other `/genux…` values change only where the value is certainly a URL.
function prefix(value, roots, certain) {
  if (!value.startsWith('/') || value.startsWith('//') || value.startsWith(ASSETS)) return null;
  if (FIXTURES.has(value.split(/[?#]/, 1)[0])) return PAGES_BASE + value;
  if (emitted(value, roots)) return null;
  const segment = value.slice(1).split(/[/?#]/, 1)[0];
  if (segment === PAGES_BASE.slice(1) && /^\/?([?#]|$)/.test(value.slice(PAGES_BASE.length)))
    return null;
  if (!segment || segment === PAGES_BASE.slice(1)) return certain ? PAGES_BASE + value : null;
  return roots.has(segment) ? PAGES_BASE + value : null;
}

// Astro's base already prefixes some public URLs (/genux/selection/forest.svg). Such a value stays
// unchanged when the path after the base is an emitted file or route under a built root and the
// authored reading, a path under an emitted genux root, is not; prefix() keeps the bare base.
function emitted(value, roots) {
  if (!value.startsWith(BASE)) return false;
  let path;
  try {
    path = decodeURIComponent(value.slice(BASE.length).split(/[?#]/, 1)[0]);
  } catch {
    return false;
  }
  if (!path || !roots.has(path.split('/', 1)[0])) return false;
  const file = rel =>
    rel.endsWith('/') ? `${rel}index.html` : posix.extname(rel) ? rel : `${rel}/index.html`;
  return roots.has(file(path)) && !roots.has(file(`${PAGES_BASE.slice(1)}/${path}`));
}

function propertyName(name) {
  return ts.isIdentifier(name) || ts.isStringLiteralLike(name) ? name.text : '';
}

// Explicit URL positions: URL-named properties, location/href assignments, location calls.
function urlContext(node) {
  const { parent } = node;
  if (ts.isPropertyAssignment(parent) && parent.initializer === node)
    return URL_KEYS.has(propertyName(parent.name));
  if (ts.isBinaryExpression(parent) && parent.right === node)
    return (
      parent.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
      /\b(location|href|pathname)$/.test(parent.left.getText())
    );
  if (ts.isCallExpression(parent) && parent.arguments[0] === node)
    return /\blocation\.(assign|replace)$/.test(parent.expression.getText());
  return false;
}

// Inserts the base after the opening quote of matching string literals and template heads, in
// reverse order; regex literals, comments and every other byte stay unchanged.
function rewriteScript(code, roots) {
  const ast = ts.createSourceFile('x.js', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const offsets = [];
  const visit = node => {
    const literal = ts.isStringLiteralLike(node) || ts.isTemplateHead(node);
    const key = ts.isPropertyAssignment(node.parent) && node.parent.name === node;
    if (literal && !key && prefix(node.text, roots, urlContext(node)) !== null)
      offsets.push(node.getStart(ast) + 1);
    ts.forEachChild(node, visit);
  };
  ts.forEachChild(ast, visit);
  let result = code;
  for (const offset of offsets.sort((a, b) => b - a))
    result = result.slice(0, offset) + PAGES_BASE + result.slice(offset);
  return result;
}

function rewriteCss(css, roots) {
  return css.replace(cssUrl, (match, quote, value) => {
    const next = prefix(value.trim(), roots, false);
    return next === null ? match : `url(${quote}${next}${quote})`;
  });
}

// Prefixes the last capture of each match: srcset candidates and meta refresh targets.
function replaceUrls(text, pattern, roots) {
  return text.replace(pattern, (all, lead, url) => lead + (prefix(url, roots, true) ?? url));
}

// Island props use Astro's [type, value] JSON pairs, so a key applies through its pair.
function rewriteProps(value, roots, key = '') {
  if (typeof value === 'string') return prefix(value, roots, URL_KEYS.has(key)) ?? value;
  if (Array.isArray(value)) return value.map(item => rewriteProps(item, roots, key));
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).map(([name, item]) => [name, rewriteProps(item, roots, name)]),
  );
}

function rewriteHtml(html, roots) {
  const dom = new JSDOM(html);
  let changed = false;
  const update = (element, name, next) => {
    if (next === element.getAttribute(name)) return;
    element.setAttribute(name, next);
    changed = true;
  };
  const setText = (element, next) => {
    if (next === element.textContent) return;
    element.textContent = next;
    changed = true;
  };
  for (const element of dom.window.document.querySelectorAll('*')) {
    for (const name of URL_ATTRIBUTES) {
      const value = element.getAttribute(name)?.trim();
      if (!value) continue;
      const url = prefix(value, roots, true) ?? value;
      if (url !== value) update(element, name, url);
    }
    const srcset = element.getAttribute('srcset');
    if (srcset) update(element, 'srcset', replaceUrls(srcset, srcsetUrl, roots));
    const style = element.getAttribute('style');
    if (style) update(element, 'style', rewriteCss(style, roots));
    const equiv = element.localName === 'meta' && element.getAttribute('http-equiv')?.trim();
    if (equiv && equiv.toLowerCase() === 'refresh') {
      const content = element.getAttribute('content') ?? '';
      update(element, 'content', replaceUrls(content, refresh, roots));
    }
    const props = element.localName === 'astro-island' && element.getAttribute('props');
    if (props) {
      const parsed = JSON.parse(props);
      const next = JSON.stringify(rewriteProps(parsed, roots));
      if (next !== JSON.stringify(parsed)) update(element, 'props', next);
    }
    if (element.localName === 'style') setText(element, rewriteCss(element.textContent, roots));
    const type = (element.getAttribute('type') ?? '').trim().toLowerCase();
    if (element.localName === 'script' && !element.hasAttribute('src') && SCRIPT_TYPES.has(type))
      setText(element, rewriteScript(element.textContent, roots));
  }
  const result = changed ? dom.serialize() : null;
  dom.window.close();
  return result;
}

// Same-site link check for the rewritten artifact, mirroring the acceptance control: external,
// data: and other-origin URLs are skipped; every other URL must stay under the base, inside the
// artifact and name an emitted readable file. Declared error-demo images are waived only while
// their demo source still declares that exact path, and must then stay unemitted.
const REPO = fileURLToPath(new URL('../', import.meta.url));
const ORIGIN = 'https://pages.invalid';
const LINKS = ['href', 'src', 'component-url', 'renderer-url', 'before-hydration-url'];
const islandUrl = /"(\/(?!\/)[^"\s]*)"/g;
const MISSING = [
  {
    rel: 'genux-avatar-missing-example.png',
    source: 'docs/src/react/AvatarDemo.tsx',
    declaration:
      /\/\/ Intentionally missing[^\n]*\nconst missingImage = '\/genux-avatar-missing-example\.png';/,
  },
  {
    rel: 'selection/missing-photo.svg',
    source: 'docs/src/react/MediaDemo.tsx',
    declaration:
      /\/\/ Local assets only; the missing path demonstrates the unavailable fallback[^\n]*\nconst missingPhoto = '\/selection\/missing-photo\.svg';/,
  },
];

function readableFile(file) {
  try {
    accessSync(file, constants.R_OK);
    return statSync(file).isFile();
  } catch {
    return false;
  }
}

function moduleSpecifier(node) {
  if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) return node.moduleSpecifier;
  if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword)
    return node.arguments[0];
  return undefined;
}

/** Throws unless every same-site URL in a published artifact names a file this build emitted. */
export async function validateArtifact(directory) {
  const out = resolve(directory);
  const missing = new Set();
  for (const { rel, source, declaration } of MISSING) {
    const file = resolve(REPO, source);
    if (existsSync(file) && declaration.test(await readFile(file, 'utf8'))) missing.add(rel);
  }
  const fail = (where, value, problem) => {
    throw new Error(`Pages artifact: ${where} links ${value}, which ${problem}.`);
  };
  const check = (value, from, where) => {
    let url;
    let rel;
    try {
      url = new URL(value, `${ORIGIN}${BASE}${from}`);
    } catch {
      fail(where, value, 'is not a valid URL');
    }
    if (url.origin !== ORIGIN) return;
    // prefix() keeps the bare hosting base /genux with any query or hash; it names the index.
    const bare = url.pathname === PAGES_BASE;
    if (!bare && !url.pathname.startsWith(BASE)) fail(where, value, `is outside ${BASE}`);
    try {
      rel = bare ? '' : decodeURIComponent(url.pathname.slice(BASE.length));
    } catch {
      fail(where, value, 'has an invalid escape');
    }
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    else if (!posix.extname(rel)) rel += '/index.html';
    const file = resolve(out, rel);
    if (!file.startsWith(out + sep)) fail(where, value, 'escapes the artifact');
    if (missing.has(rel)) {
      if (existsSync(file)) fail(where, value, 'its demo declares missing, yet this build emits');
    } else if (!readableFile(file)) fail(where, value, 'this build did not emit');
  };
  const cssUrls = (css, from, where) => {
    for (const [, , value] of css.matchAll(cssUrl)) check(value.trim(), from, where);
  };
  const entries = await readdir(out, { recursive: true, withFileTypes: true });
  const paths = entries
    .filter(entry => entry.isFile())
    .map(entry => relative(out, resolve(entry.parentPath, entry.name)).split(sep).join('/'));
  for (const from of paths.sort()) {
    if (!/\.(html|m?js|css)$/.test(from)) continue;
    const source = await readFile(resolve(out, from), 'utf8');
    if (from.endsWith('.css')) cssUrls(source, from, `${from} css url()`);
    else if (from.endsWith('.html')) {
      const dom = new JSDOM(source);
      try {
        const { document } = dom.window;
        const linked = '[href], [src], [srcset], [style], astro-island';
        for (const element of document.querySelectorAll(linked)) {
          for (const name of LINKS) {
            const value = element.getAttribute(name);
            if (value) check(value, from, `${from} ${name}`);
          }
          for (const part of (element.getAttribute('srcset') ?? '').split(',')) {
            const value = part.trim().split(/\s+/)[0];
            if (value) check(value, from, `${from} srcset`);
          }
          cssUrls(element.getAttribute('style') ?? '', from, `${from} style`);
          for (const [, value] of (element.getAttribute('props') ?? '').matchAll(islandUrl))
            check(value, from, `${from} island props`);
        }
        for (const style of document.querySelectorAll('style'))
          cssUrls(style.textContent, from, `${from} css url()`);
      } finally {
        dom.window.close();
      }
    } else {
      const ast = ts.createSourceFile(
        from,
        source,
        ts.ScriptTarget.Latest,
        false,
        ts.ScriptKind.JS,
      );
      const visit = node => {
        const spec = moduleSpecifier(node);
        if (spec && ts.isStringLiteralLike(spec)) check(spec.text, from, `${from} module import`);
        ts.forEachChild(node, visit);
      };
      visit(ast);
    }
  }
}

/** Prefixes a fresh Pages build in place and returns how many files changed. */
export async function publishPages(directory) {
  const files = [];
  for (const entry of await readdir(directory, { recursive: true, withFileTypes: true }))
    if (entry.isFile()) files.push(resolve(entry.parentPath, entry.name));
  for (const file of files) {
    const path = relative(directory, file).split(sep).join('/');
    if (PRIVATE.test(path)) throw new Error(`Pages artifact must not publish ${path}.`);
  }
  const roots = new Set((await readdir(directory)).filter(name => !name.startsWith('.')));
  // Emitted files under those roots let prefix() recognise URLs Astro already based.
  for (const file of files) {
    const path = relative(directory, file).split(sep).join('/');
    if (roots.has(path.split('/', 1)[0])) roots.add(path);
  }
  let count = 0;
  for (const file of files.sort()) {
    if (!/\.(html|m?js|css)$/.test(file)) continue;
    const source = await readFile(file, 'utf8');
    let next;
    if (file.endsWith('.html')) next = rewriteHtml(source, roots);
    else if (file.endsWith('.css')) next = rewriteCss(source, roots);
    else next = rewriteScript(source, roots);
    if (next === null || next === source) continue;
    await writeFile(file, next);
    count++;
  }
  // Publication fails before upload unless the rewritten artifact is complete.
  await validateArtifact(directory);
  await writeFile(resolve(directory, '.nojekyll'), '');
  return count;
}

/** Astro integration for GENUX_DOCS_PAGES=1; order it after the presentation gate. */
export default function docsPages() {
  return {
    name: 'genux-docs-pages',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const count = await publishPages(fileURLToPath(dir));
        logger.info(`GitHub Pages adapter: ${count} files prefixed for ${PAGES_SITE}${BASE}.`);
      },
    },
  };
}
