// Generates the Sass view of the single adaptive policy JSON. Thresholds live only in that
// file; `--check` compares the committed partial and fails without writing when it is stale.
// Output goes through the project Prettier config so generation and check agree with
// docs:format; the raw rendering is also accepted as current.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const policyPath = 'docs/src/adaptive/policy.json';
export const outputPath = 'docs/src/styles/generated/_adaptive-policy.scss';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requiredWidths = [
  'base',
  'widePhone',
  'smallTablet',
  'tablet',
  'laptop',
  'desktop',
  'wideDesktop',
  'ultraWide',
  'expansive',
];

const kebab = name => name.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
const px = value => `${value}px`;

function readScale(policy, field) {
  const scale = policy[field];
  if (scale === null || typeof scale !== 'object' || Array.isArray(scale)) {
    throw new Error(`Adaptive policy ${field} must be an object of named widths.`);
  }
  const entries = Object.entries(scale);
  let previous = 0;
  for (const [name, value] of entries) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(name)) {
      throw new Error(`Adaptive policy ${field}.${name} must be a camelCase name.`);
    }
    if (!Number.isInteger(value) || value <= previous) {
      throw new Error(`Adaptive policy ${field}.${name} must be an integer above ${previous}.`);
    }
    previous = value;
  }
  return entries;
}

function scssMap(name, entries, format) {
  const rows = entries.map(([key, value]) => `  ${kebab(key)}: ${format(value)},`);
  return [`$${name}: (`, ...rows, ');'].join('\n');
}

export function renderAdaptivePolicyScss(policy) {
  if (policy === null || typeof policy !== 'object' || policy.version !== 1) {
    throw new Error('Adaptive policy version must be 1.');
  }
  const widths = readScale(policy, 'widths');
  const antd = readScale(policy, 'antd');
  const missing = requiredWidths.filter(name => !Object.hasOwn(policy.widths, name));
  if (missing.length > 0) throw new Error(`Adaptive policy widths lack ${missing.join(', ')}.`);
  if (!Number.isInteger(policy.shortHeight) || policy.shortHeight <= 0) {
    throw new Error('Adaptive policy shortHeight must be a positive integer.');
  }
  return [
    `// Generated by tools/adaptive-styles.mjs from ${policyPath}; do not edit.`,
    `$version: ${policy.version};`,
    scssMap('widths', widths, px),
    scssMap('antd', antd, px),
    `$short-height: ${px(policy.shortHeight)};`,
    scssMap('media-min', widths, value => `'(width >= ${px(value)})'`),
    `$media-short: '(height < ${px(policy.shortHeight)})';`,
    '',
  ].join('\n');
}

// Prettier is loaded lazily so importing the renderer stays dependency-free.
export async function formatAdaptivePolicyScss(source, target = resolve(root, outputPath)) {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(source, { ...options, filepath: target });
}

export function isAdaptivePolicyCurrent(current, rendered, formatted) {
  return current !== null && (current === formatted || current === rendered);
}

export async function main(args = process.argv.slice(2)) {
  const unknown = args.filter(arg => arg !== '--check');
  if (unknown.length > 0) throw new Error(`Unknown argument ${unknown.join(' ')}.`);
  const policy = JSON.parse(await readFile(resolve(root, policyPath), 'utf8'));
  const rendered = renderAdaptivePolicyScss(policy);
  const target = resolve(root, outputPath);
  const formatted = await formatAdaptivePolicyScss(rendered, target);
  const current = await readFile(target, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (isAdaptivePolicyCurrent(current, rendered, formatted)) return true;
  if (args.includes('--check')) {
    console.error(`${outputPath} is stale; run npm run docs:adaptive:styles:generate.`);
    process.exitCode = 1;
    return false;
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, formatted);
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
